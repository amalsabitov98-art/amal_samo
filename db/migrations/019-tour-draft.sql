-- 019-tour-draft.sql
-- Черновики туров и надзаголовок карточки.
--
-- Зачем:
--   published_at — новый тур больше не попадает в публичный каталог в
--   момент создания. NULL значит «ни разу не публиковался» = черновик,
--   виден только оператору. Отдельного поля статуса нет намеренно:
--   «черновик» и «снят с продажи» — это is_bookable = 0 в обоих случаях,
--   различает их ровно факт публикации, и второе поле рано или поздно
--   разъехалось бы с is_bookable.
--
--   kicker — строка над названием на публичной карточке. Она была зашита
--   в js/catalog.js как `destination === "Умра" ? … : "Загадочный
--   Карадениз"`, поэтому ЛЮБОЙ новый тур выходил подписанным Караденизом.
--
-- ВНИМАНИЕ: НЕ идемпотентна. В SQLite нет ADD COLUMN IF NOT EXISTS,
-- повторный прогон падает с «duplicate column name». Отказ безопасный —
-- данные не меняются, — но гнать один раз.
--
-- Прогон (на стороне оператора, wrangler залогинен):
--   cd worker
--   wrangler d1 execute turon-tour --remote --file=../db/migrations/019-tour-draft.sql

ALTER TABLE tours ADD COLUMN published_at TEXT;
ALTER TABLE tours ADD COLUMN kicker TEXT;

-- Уже продающиеся туры черновиками стать не должны: без этой строки они
-- показались бы оператору как неопубликованные, а кнопка «Опубликовать»
-- потребовала бы заполнить то, что у них и так заполнено.
UPDATE tours SET published_at = datetime('now')
 WHERE is_bookable = 1 AND published_at IS NULL;

-- Надзаголовки, которые до сих пор рисовались из кода. Без них карточки
-- существующих туров потеряли бы строку, которая на них сейчас есть.
UPDATE tours SET kicker = 'Загадочный Карадениз' WHERE code = 'KARADENIZ';
UPDATE tours SET kicker = 'Умра · Мекка и Медина' WHERE destination = 'Умра';

-- То же самое имя, что в 011-rename-karadeniz.sql. Повтор намеренный:
-- вместе с этой миграцией из js/catalog.js убирается TITLE_OVERRIDES,
-- который подставлял новое имя прямо в браузере. Если 011 на живой базе
-- так и не прогнали, без этой строки карточка после выкатки показала бы
-- старое имя «Карадениз — Трабзон и Ризе». UPDATE по коду идемпотентен.
UPDATE tours SET name = 'Батуми - Ризе - Трабзон' WHERE code = 'KARADENIZ';
