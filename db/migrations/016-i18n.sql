-- 016 — переводы контента каталога (uz / en / tr).
--
-- Русский остаётся в обычных колонках и служит ОТКАТОМ: у тура, только что
-- заведённого оператором, переводов нет вовсе, и без отката его карточка на
-- английском вышла бы с пустой программой и пустым «включено».
--
-- Хранение — одна колонка i18n с JSON на строку, а не name_uz/name_en/name_tr
-- по колонке на каждый язык. Причина: пятый язык или новое переводимое поле
-- иначе означали бы новую миграцию И правку каждого INSERT/UPDATE в воркере.
-- Формат: {"uz":{"поле":"значение",…},"en":{…},"tr":{…}} — язык верхним
-- ключом, чтобы «дай мне всё по-турецки» было одним обращением.
--
-- НЕ ИДЕМПОТЕНТНА: в SQLite нет ADD COLUMN IF NOT EXISTS, повторный прогон
-- упадёт с «duplicate column name». Это безопасный отказ — данные не
-- меняются, — но прогонять её нужно ровно один раз.
--
-- Заезды, цены, брони и агентства не затрагиваются вообще.

ALTER TABLE tours         ADD COLUMN i18n TEXT;
ALTER TABLE destinations  ADD COLUMN i18n TEXT;
ALTER TABLE tour_variants ADD COLUMN i18n TEXT;
ALTER TABLE tour_content  ADD COLUMN i18n TEXT;
