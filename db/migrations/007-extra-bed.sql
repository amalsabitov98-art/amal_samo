-- 007: доп. кровать в двухместном номере (DBL+1) как тип размещения.
--
-- Оказалось, что оператор иногда может поставить в двухместный номер
-- дополнительную кровать. Отдельного тарифа на это в ведомости нет ни у
-- одного заезда, поэтому строка прайса заводится здесь.
--
-- ЦЕНА ВРЕМЕННАЯ. Она приравнена к TRPL — ближайшему реальному тарифу
-- оператора («третий в номере»), а не взята с потолка. Настоящую цену
-- обещали уточнить; когда дадут — см. блок EXTRA_BED_* в
-- tools/build-seed.py и миграцию 008 для боевой базы.
--
-- Место в самолёте доп. кровать занимает (occupies_seat = 1): это живой
-- пассажир, который летит и считается в capacity заезда.
--
-- Идемпотентна: сначала удаляет свои же строки, потом вставляет заново,
-- поэтому повторный запуск и запуск после смены цены дают один результат.
-- Брони, места и агентства не трогает — только справочник цен. Уже
-- созданные брони сохраняют свою цену: она зафиксирована в passengers.price
-- на момент бронирования и из departure_prices не перечитывается.
--
-- Применять:
--   cd worker
--   wrangler d1 execute turon-tour --remote --file=../db/migrations/007-extra-bed.sql

DELETE FROM departure_prices WHERE code = 'DBLX';

INSERT INTO departure_prices
  (departure_id, code, label, kind, price, age_from, age_to, occupies_seat)
SELECT p.departure_id, 'DBLX', 'Доп. кровать (DBL+1)', 'placement',
       p.price, NULL, NULL, 1
  FROM departure_prices p
 WHERE p.kind = 'placement' AND p.code = 'TRPL';
